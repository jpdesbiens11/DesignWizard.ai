export const ANNEXES = SKILLS["ergonomie-ui"].annexes;
const body = (text) => text.replace(/^---\n[\s\S]*?\n---\n+/, ""), untitled = (text) => text.replace(/^# .*\n+/, ""), titleOf = (text) => (text.match(/^# (.*)$/m) || [])[1] || "";

/** The single file of a skill, as text. */
export function singleFile(name = "ergonomie-ui") {
  const S = SKILLS[name], read = (p) => readFileSync(path.join(root, "skills", name, p), "utf8");
  const skill = body(read("SKILL.md")), letter = Object.fromEntries(S.annexes.map(([l, file]) => [file, l]));
  const main = untitled(skill).replace(/\[references\/([\w-]+)\.md\]\(references\/\1\.md\)/g, (_, file) => S.link(letter[file]));
  const out = [...S.head(name), "", `# ${titleOf(skill)} — ${S.title}`, "", ...S.intro(name), "", main.trimEnd(), ""];
  for (const [l, file] of S.annexes) { const text = read(`references/${file}.md`); out.push("---", "", `# ${S.annexe} ${l} — ${titleOf(text)}`, "", untitled(text).trimEnd(), ""); }
  return out.join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) for (const name of Object.keys(SKILLS)) { writeFileSync(path.join(root, "skills", `${name}.md`), singleFile(name)); console.log(`skills/${name}.md written`); }
