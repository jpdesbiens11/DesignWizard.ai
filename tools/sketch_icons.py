"""Functional icons of DynamiteOrbit, drawn on a 24-unit grid (see tools/make_sketch_assets.py).

ICONS maps a name to a list of shapes understood by sketch_rough.Pen.stroke(); the sprite exposes each one as
<symbol id="i-NAME" viewBox="0 0 24 24">, stroke = currentColor. Keep every coordinate within 2.5 … 21.5 so that the
pencil overshoot is never clipped by the viewBox. No text: letters (the « i » of info, the « ! » of warning) are strokes.
"""
import math

from sketch_rough import arc_points, gear_points, star_points

PI = math.pi


def bolt(x, y, s=1.0):
    """Lightning bolt (power)."""
    return ("poly", [(x + 1.2 * s, y), (x - 1.6 * s, y + 4.2 * s), (x + 0.4 * s, y + 4.2 * s), (x - 0.8 * s, y + 8 * s),
                     (x + 2.4 * s, y + 3.2 * s), (x + 0.3 * s, y + 3.2 * s)], True)


def head(x, y, dx, dy, size=2.4):
    """Open arrow head whose tip is (x, y), pointing along (dx, dy) (a unit axis vector)."""
    return ("poly", [(x - dx * size - dy * size, y - dy * size - dx * size), (x, y),
                     (x - dx * size + dy * size, y - dy * size + dx * size)], False)


def half_link(cx, cy, r, ext, side):
    """Half chain link: a « C » opened towards side (+1 = right, -1 = left)."""
    arc = arc_points(cx, cy, r, r, -PI / 2, -PI * side, 6)
    return ("curve", [(cx + ext * side, cy - r)] + arc + [(cx + ext * side, cy + r)], False)


